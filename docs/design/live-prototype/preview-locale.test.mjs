import test from 'node:test';
import assert from 'node:assert/strict';
import { readPreviewRoute, previewPageHref, initPreview } from './preview.js';

test('preview routes normalize locale and page while preserving the fragment', () => {
  const route = readPreviewRoute('https://example.test/live-prototype/?page=kip&lang=en#proof');
  assert.deepEqual(route, { page: 'kip', locale: 'en', hash: 'proof' });
  assert.equal(previewPageHref(route), 'page.html?page=kip&lang=en#proof');
  assert.deepEqual(readPreviewRoute('?page=oops&lang=missing#contact'), { page: 'home', locale: 'zh-Hant', hash: 'contact' });
  assert.equal(previewPageHref(readPreviewRoute('?lang=en#%E8%B3%87%E6%96%99')), 'page.html?page=home&lang=en#%E8%B3%87%E6%96%99');
  assert.equal(previewPageHref(readPreviewRoute('?lang=en#%broken')), 'page.html?page=home&lang=en#%25broken');
});

test('preview shell localizes and stays synchronized with iframe navigation and language changes', () => {
  function element() { return { value: '', style: {}, dataset: {}, handlers: {}, textContent: '', addEventListener(type, callback) { this.handlers[type] = callback; }, removeEventListener() {} }; }
  const ids = Object.fromEntries(['stage', 'viewport', 'preview', 'width', 'page', 'language', 'fit', 'readout', 'direct', 'status', 'metrics'].map(id => [id, element()]));
  ids.width.value = '1440';
  Object.assign(ids.stage, { clientWidth: 1000, clientHeight: 800 });
  const labels = ['title', 'page', 'language', 'width', 'fit', 'direct'].map(key => ({ dataset: { previewLabel: key }, textContent: '' }));
  const options = [{ value: 'home', textContent: '' }, { value: 'kip', textContent: '' }];
  ids.page.options = options;
  const document = { title: '', documentElement: {}, getElementById: id => ids[id], querySelectorAll: () => labels };
  const window = { location: new URL('https://example.test/live-prototype/?page=kip&lang=en#proof'), handlers: {}, addEventListener(type, callback) { this.handlers[type] = callback; }, removeEventListener() {}, requestAnimationFrame(callback) { callback(); }, setInterval: () => 1, clearInterval() {} };
  window.history = { replaceState(_state, _title, href) { window.location = new URL(href, window.location); } };
  const iframeWindow = { location: new URL('https://example.test/live-prototype/page.html?page=kip&lang=en#proof'), handlers: {}, addEventListener(type, callback) { this.handlers[type] = callback; }, removeEventListener() {} };
  ids.preview.contentWindow = iframeWindow;
  ids.preview.contentDocument = { querySelector: () => true, documentElement: { clientWidth: 1440, scrollWidth: 1440 } };
  const dispose = initPreview({ document, window, ResizeObserver: class { observe() {} disconnect() {} } });
  assert.equal(ids.preview.src, 'page.html?page=kip&lang=en#proof');
  assert.equal(document.documentElement.lang, 'en');
  assert.equal(document.title, 'SynaiQ / Design prototype');
  assert.equal(options[1].textContent, 'KIP Platform');
  assert.match(ids.status.textContent, /Page width 1440px/);
  ids.preview.handlers.load();
  iframeWindow.location.hash = '#architecture';
  iframeWindow.handlers.hashchange();
  assert.match(ids.direct.href, /#architecture$/);
  assert.equal(window.location.hash, '#architecture');
  ids.language.value = 'zh-Hant';
  ids.language.handlers.change();
  assert.equal(ids.preview.src, 'page.html?page=kip&lang=zh-Hant#architecture');
  assert.equal(document.documentElement.lang, 'zh-Hant');
  ids.page.value = 'home';
  ids.page.handlers.change();
  assert.equal(ids.preview.src, 'page.html?page=home&lang=zh-Hant');
  ids.width.value = '390';
  ids.width.handlers.input();
  assert.equal(ids.viewport.style.width, '390px');
  assert.equal(ids.readout.value, '390 px');
  iframeWindow.location = new URL('https://example.test/live-prototype/page.html?page=home&lang=en#contact');
  ids.preview.handlers.load();
  assert.equal(ids.language.value, 'en');
  assert.equal(ids.page.value, 'home');
  assert.match(ids.metrics.textContent, /No horizontal overflow/);
  ids.preview.contentDocument.documentElement.scrollWidth = 1500;
  ids.width.handlers.input();
  assert.match(ids.metrics.textContent, /Horizontal overflow/);
  ids.fit.handlers.click();
  assert.equal(ids.width.value, '968');
  ids.width.value = '2000';
  window.handlers.resize();
  assert.equal(ids.width.value, '1600');
  ids.width.value = 'invalid';
  window.handlers.resize();
  assert.equal(ids.width.value, '1440');
  window.location = new URL('https://example.test/live-prototype/?page=kip&lang=en#process');
  window.handlers.popstate();
  assert.equal(ids.preview.src, 'page.html?page=kip&lang=en#process');
  iframeWindow.location = new URL('https://external.test/page.html?page=home&lang=zh-Hant');
  ids.preview.handlers.load();
  assert.equal(ids.page.value, 'kip', 'An external iframe location must not change the shell route');
  iframeWindow.location = new URL('https://example.test/unrelated.html?page=home&lang=zh-Hant');
  ids.preview.handlers.load();
  assert.equal(ids.language.value, 'en');
  ids.preview.contentDocument = null;
  ids.width.handlers.input();
  assert.equal(ids.metrics.textContent, 'Waiting for the prototype');
  Object.defineProperty(ids.preview, 'contentDocument', { configurable: true, get() { throw new Error('Blocked'); } });
  ids.width.handlers.input();
  assert.equal(ids.metrics.textContent, 'Waiting for the prototype');
  dispose();
});
